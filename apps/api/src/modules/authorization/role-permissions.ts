export type GlobalRole = "PLATFORM_ADMIN" | "PLATFORM_USER";

/**
 * Normalise les anciennes valeurs conservées pour la compatibilité des
 * jetons/données. Un ADMIN historique est traité comme PLATFORM_ADMIN.
 */
export function normalizeGlobalRole(role: Role | string): GlobalRole {
  if (role === Role.PLATFORM_ADMIN || role === Role.ADMIN) {
    return "PLATFORM_ADMIN";
  }
  return "PLATFORM_USER";
}

export function isPlatformAdmin(role: Role | string): boolean {
  return normalizeGlobalRole(role) === "PLATFORM_ADMIN";
}

